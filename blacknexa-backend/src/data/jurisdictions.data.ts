/** Set of curated country codes for fast lookup. */
export const CURATED_COUNTRIES = new Set(JURISDICTIONS.map((j) => j.code));

/** Build a JurisdictionProfile from the curated seed. */
export function getCuratedProfile(countryCode: string): JurisdictionProfile | null {
  const seed = JURISDICTIONS.find(
    (j) => j.code === countryCode.toUpperCase(),
  );
  if (!seed) return null;
  return {
    countryCode: seed.code,
    countryName: seed.name,
    primaryLanguage: seed.primaryLanguage,
    privacyRegime: seed.privacyRegime,
    legalFrameworks: seed.frameworks,
    agencies: seed.agencies,
    pressContacts: seed.press,
    source: "curated",
    generatedAt: new Date().toISOString(),
  };
}

/** List all curated jurisdiction codes — used for the refresh endpoint. */
export function listCuratedCountries(): string[] {
  return JURISDICTIONS.map((j) => j.code);
}
