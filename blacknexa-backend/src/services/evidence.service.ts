/**
 * Evidence upload, sealing and access.
 *
 * ── Why the transport changed ──────────────────────────────────────────────
 * The geo-legal module took evidence as base64 inside a JSON body. Screen C5
 * attaches a 24.8 MB video with per-file progress, which that cannot do: base64
 * inflates by a third, gives no progress, cannot resume, and breaches the JSON
 * body limit. So the flow is presign → direct PUT → commit.
 *
 * ── What "Sealed" means ────────────────────────────────────────────────────
 * On commit the server reads the stored object, hashes it, and compares that to
 * the SHA-256 the client declared. Only then is `sealed_at` stamped. That single
 * server-side timestamp is what C5, C9, D3, D11 and D12 all render — there is no
 * client-supplied seal time anywhere, because a timestamp the client chooses
 * proves nothing about when the file arrived or whether it changed.
 *
 * A mismatch is refused, not logged and accepted: the whole trust story on D3
 * rests on "Nothing has changed since", and a file we cannot vouch for must not
 * be able to claim that.
 *
 * ── Revision 2 (docs/INCIDENT_MODULE_PLAN.md §7.1, §7.3, §7.9, D22) ────────
 *   • **Ownership.** Presign used to accept any `reportId` or `draftId`, so any
 *     member could attach — and seal — files onto someone else's report, and the
 *     draft file list answered for any draft UUID. Every entry point now resolves
 *     the target through the caller's own draft or report, or answers 404.
 *   • **One lock with filing.** Presign, commit and remove lock the same draft row
 *     filing locks (`SELECT … FOR UPDATE`). No file can be attached, sealed or
 *     removed while its draft is being filed, the per-report caps cannot be raced
 *     past, and once filing has consumed a draft every later call on it is a 404.
 *     The hash itself is computed *before* the lock is taken, so a slow download
 *     of a large file never holds up the draft.
 *   • **Moderation state (D22).** A file has its own `moderation_state`, written
 *     explicitly at presign: `pending` (a draft's files are re-stated by
 *     visibility at filing), or `approved` for a private report, which is never
 *     sent to the AI (D3). Non-owners are sent a URL only for an approved file;
 *     a pending one is listed "Awaiting review" with no URL; a rejected file or a
 *     failed upload is not listed to them at all.
 *   • **Late files.** A file sealed onto an already-filed moderated report
 *     queues an `evidence` run in the sealing transaction when no queued run
 *     would otherwise read it, so it is assessed rather than left waiting for a
 *     moderator (§5.1). A report still waiting for the human check its last
 *     resubmission promised gets a `resubmitted` run instead (D19, review R1),
 *     and an urgent report keeps its urgent priority and short retry budget
 *     (D5/D21, review R2).
 *
 * ── Approval is bound to the bytes that are served (review R5) ────────────
 * The AI assesses a photo through its preview, and the preview is generated by
 * the client — it was never hashed or tied to the original, while non-owners
 * were served the original. Worse, the presigned PUT URLs stay valid for
 * `S3_PRESIGN_EXPIRES_SECONDS`, so both objects could be replaced *after* an
 * approval. Three rules close that:
 *
 *   1. **Sealing moves the bytes.** Commit reads the original (and the preview,
 *      when one was uploaded), hashes both, and copies each to a fresh
 *      `sealed/<uuid>` key that no presigned PUT was ever issued for — the copy
 *      conditional on the ETag that was hashed, so a re-PUT in between fails the
 *      seal instead of sealing unverified bytes. The row is repointed at the
 *      sealed keys (with `thumb_sha256`), and the upload keys are deleted after
 *      the commit. A failed copy marks the row `failed`; nothing is half-moved.
 *   2. **An approval names its scope.** `approveEvidence` records `full` (the
 *      original was assessed) or `thumbnail` (only the sealed preview was).
 *   3. **Non-owners get exactly the approved bytes.** `thumbnail` scope serves
 *      `thumbUrl` alone with `fullResolutionPending`; `full` serves both. Owners
 *      and staff always get both. The rule is `evidenceAccessFor` in
 *      `report_visibility.ts`, applied by `toView` itself for a member audience.
 */

